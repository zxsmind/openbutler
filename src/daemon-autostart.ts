import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { getDataPath } from './paths.js';
import { loadSettings } from './settings.js';
import { removeTelegramEnvFile, telegramEnvFilePath, writeTelegramEnvFile } from './telegram-setup.js';

const MANAGED_MARKER = 'Managed by OpenButler. Do not edit this file.';
const WINDOWS_RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run';
const WINDOWS_RUN_VALUE = 'OpenButler';
const MACOS_LABEL = 'ai.openbutler.agent';
const LINUX_UNIT_NAME = 'openbutler.service';

export function autostartDescription(): string {
  if (process.platform === 'win32') return 'Current Windows user logon';
  if (process.platform === 'darwin') return 'Current macOS user login';
  if (process.platform === 'linux') return 'Current Linux user session (systemd)';
  return `Unsupported platform: ${process.platform}`;
}

export function isAutostartInstalled(): boolean {
  if (process.platform === 'win32') {
    const value = readWindowsRunValue();
    return value !== null && value.includes(getWindowsLauncherPath());
  }
  const path = getAutostartFilePath();
  try {
    return readFileSync(path, 'utf8').includes(MANAGED_MARKER);
  } catch {
    return false;
  }
}

export function installAutostart(): string {
  const { executable, entry } = getCliCommand();
  if (process.platform === 'win32') return installWindows(executable, entry);
  if (process.platform === 'darwin') return installMacos(executable, entry);
  if (process.platform === 'linux') return installLinux(executable, entry);
  throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
}

export function uninstallAutostart(): string {
  if (process.platform === 'win32') return uninstallWindows();
  if (process.platform === 'darwin') return uninstallMacos();
  if (process.platform === 'linux') return uninstallLinux();
  throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
}

function installWindows(executable: string, entry: string): string {
  const launcher = getWindowsLauncherPath();
  const existing = readWindowsRunValue();
  if (existing !== null && !existing.includes(launcher)) {
    throw new Error(`The Windows Run value "${WINDOWS_RUN_VALUE}" already belongs to another command; OpenButler left it unchanged.`);
  }
  mkdirSync(dirname(launcher), { recursive: true });
  const command = `${quoteWindowsArgument(executable)} ${quoteWindowsArgument(entry)} daemon run`;
  const script = [
    `' ${MANAGED_MARKER}`,
    'Set openbutlerShell = CreateObject("WScript.Shell")',
    `openbutlerShell.Environment("PROCESS")("OPENBUTLER_DATA_DIR") = "${resolve(getDataPath()).replace(/"/g, '""')}"`,
    `openbutlerShell.Run "${command.replace(/"/g, '""')}", 0, False`,
    '',
  ].join('\r\n');
  writeAtomically(launcher, script);
  try {
    runCommand('reg.exe', ['add', WINDOWS_RUN_KEY, '/v', WINDOWS_RUN_VALUE, '/t', 'REG_SZ', '/d', `wscript.exe "${launcher}"`, '/f']);
  } catch (error) {
    unlinkIfExists(launcher);
    throw error;
  }
  return `${autostartDescription()} configured.`;
}

function uninstallWindows(): string {
  const launcher = getWindowsLauncherPath();
  const existing = readWindowsRunValue();
  if (existing === null || !existing.includes(launcher)) return 'OpenButler automatic startup was not installed.';
  runCommand('reg.exe', ['delete', WINDOWS_RUN_KEY, '/v', WINDOWS_RUN_VALUE, '/f']);
  unlinkIfExists(launcher);
  return 'OpenButler automatic startup removed.';
}

function installMacos(executable: string, entry: string): string {
  const path = getAutostartFilePath();
  assertManagedFileCanBeReplaced(path);
  const logPath = getDataPath('daemon.log');
  mkdirSync(dirname(logPath), { recursive: true });
  writeAtomically(path, buildMacosDocument(executable, entry, resolve(getDataPath()), logPath, telegramExtraEnv()));
  return `${autostartDescription()} configured.`;
}

function uninstallMacos(): string {
  const path = getAutostartFilePath();
  if (!isAutostartInstalled()) return 'OpenButler automatic startup was not installed.';
  const domain = `gui/${requireUid()}`;
  const loaded = spawnSync('launchctl', ['print', `${domain}/${MACOS_LABEL}`], { encoding: 'utf8' });
  if (loaded.error) throw loaded.error;
  if (loaded.status === 0) runCommand('launchctl', ['bootout', domain, path]);
  unlinkIfExists(path);
  return 'OpenButler automatic startup removed.';
}

function installLinux(executable: string, entry: string): string {
  const path = getAutostartFilePath();
  assertManagedFileCanBeReplaced(path);
  writeAutostartUnit(path, executable, entry);
  try {
    runCommand('systemctl', ['--user', 'daemon-reload']);
    runCommand('systemctl', ['--user', 'enable', LINUX_UNIT_NAME]);
  } catch (error) {
    try {
      runCommand('systemctl', ['--user', 'disable', '--now', LINUX_UNIT_NAME]);
    } catch {
      /* retain original error */
    }
    unlinkIfExists(path);
    try {
      runCommand('systemctl', ['--user', 'daemon-reload']);
    } catch {
      /* retain original error */
    }
    throw error;
  }
  return `${autostartDescription()} configured.`;
}

function uninstallLinux(): string {
  const path = getAutostartFilePath();
  if (!isAutostartInstalled()) return 'OpenButler automatic startup was not installed.';
  runCommand('systemctl', ['--user', 'disable', '--now', LINUX_UNIT_NAME]);
  unlinkIfExists(path);
  removeTelegramEnvFile(telegramEnvFilePath(resolve(getDataPath())));
  runCommand('systemctl', ['--user', 'daemon-reload']);
  return 'OpenButler automatic startup removed.';
}

/**
 * Pure LaunchAgent document builder. `extraEnv` carries secret-class values
 * (today: the Telegram bot token) inline; the file is always written 0600.
 */
export function buildMacosDocument(
  executable: string,
  entry: string,
  dataDir: string,
  logPath: string,
  extraEnv: Record<string, string>,
): string {
  for (const name of Object.keys(extraEnv)) assertEnvName(name);
  const variables = [`<key>OPENBUTLER_DATA_DIR</key><string>${xmlEscape(dataDir)}</string>`];
  for (const [name, value] of Object.entries(extraEnv)) variables.push(`<key>${name}</key><string>${xmlEscape(value)}</string>`);
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    `  <key>Label</key><string>${xmlEscape(MACOS_LABEL)}</string>`,
    `  <key>Comment</key><string>${xmlEscape(MANAGED_MARKER)}</string>`,
    '  <key>ProgramArguments</key>',
    '  <array>',
    `    <string>${xmlEscape(executable)}</string>`,
    `    <string>${xmlEscape(entry)}</string>`,
    '    <string>daemon</string>',
    '    <string>run</string>',
    '  </array>',
    `  <key>EnvironmentVariables</key><dict>${variables.join('')}</dict>`,
    '  <key>RunAtLoad</key><true/>',
    '  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>',
    `  <key>StandardOutPath</key><string>${xmlEscape(logPath)}</string>`,
    `  <key>StandardErrorPath</key><string>${xmlEscape(logPath)}</string>`,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

/**
 * Pure systemd unit builder. Secrets never go inline: when `envFile` is set
 * the unit reads an optional (`-` prefix) 0600 env file instead, so deleting
 * the file cleanly unwires the secret without touching the unit.
 */
export function buildLinuxUnit(executable: string, entry: string, dataDir: string, envFile: string | null): string {
  return [
    '[Unit]',
    'Description=OpenButler personal agent host',
    '',
    '[Service]',
    'Type=simple',
    `# ${MANAGED_MARKER}`,
    `ExecStart=${systemdQuote(executable)} ${systemdQuote(entry)} daemon run`,
    `Environment=${systemdQuote(`OPENBUTLER_DATA_DIR=${dataDir}`, false)}`,
    ...(envFile === null ? [] : [`EnvironmentFile=-${systemdQuote(envFile, false)}`]),
    'Restart=on-failure',
    'RestartSec=3',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n');
}

/** Telegram token currently available to this process, if Telegram is configured. */
export function currentTelegramEnv(): { name: string; value: string } | null {
  const telegram = loadSettings().telegram;
  if (!telegram?.enabled) return null;
  const value = process.env[telegram.tokenEnv]?.trim();
  if (!value) return null;
  return { name: telegram.tokenEnv, value };
}

/** Telegram token as plist `EnvironmentVariables` entries (macOS only). */
function telegramExtraEnv(): Record<string, string> {
  const telegram = currentTelegramEnv();
  return telegram === null ? {} : { [telegram.name]: telegram.value };
}

function writeAutostartUnit(path: string, executable: string, entry: string): void {
  const dataDir = resolve(getDataPath());
  if (process.platform === 'darwin') {
    writeAtomically(path, buildMacosDocument(executable, entry, dataDir, getDataPath('daemon.log'), telegramExtraEnv()));
    return;
  }
  const telegram = currentTelegramEnv();
  let envFile: string | null = null;
  if (telegram !== null) {
    envFile = telegramEnvFilePath(dataDir);
    writeTelegramEnvFile(envFile, telegram.name, telegram.value);
  }
  writeAtomically(path, buildLinuxUnit(executable, entry, dataDir, envFile));
}

/**
 * Rewires an already-installed login startup entry for the current Telegram
 * token state: adds the wiring when a token is available, removes it when
 * Telegram is unconfigured. Never touches user-modified files and never
 * restarts a running host — rewritten units apply at the next login.
 */
export function refreshAutostartEnv(): { updated: boolean; detail: string } {
  if (currentTelegramEnv() === null) removeTelegramEnvFileIfUnused();
  if (process.platform === 'win32')
    return { updated: false, detail: 'Windows login startup inherits the user environment; nothing to update.' };
  if (process.platform !== 'darwin' && process.platform !== 'linux')
    return { updated: false, detail: 'Login startup is not supported on this platform.' };
  if (!isAutostartInstalled())
    return {
      updated: false,
      detail:
        'Automatic startup is not installed; the token applies to the current host. Run `openbutler daemon install` to also cover user login.',
    };
  const path = getAutostartFilePath();
  try {
    assertManagedFileCanBeReplaced(path);
  } catch {
    return {
      updated: false,
      detail: `Login startup file is user-modified, left unchanged: ${path}. Wire the token variable there manually.`,
    };
  }
  const { executable, entry } = getCliCommand();
  writeAutostartUnit(path, executable, entry);
  if (process.platform === 'linux') {
    try {
      runCommand('systemctl', ['--user', 'daemon-reload']);
    } catch (error) {
      return {
        updated: true,
        detail: `Login unit rewritten, but daemon-reload failed: ${error instanceof Error ? error.message : String(error)}`,
      };
    }
    removeTelegramEnvFileIfUnused();
    return { updated: true, detail: 'Login unit rewritten for the current token state; applies at the next user login.' };
  }
  return { updated: true, detail: 'Login agent rewritten for the current token state; applies at the next user login.' };
}

/** Deletes the systemd env file when no Telegram token is configured anymore. */
function removeTelegramEnvFileIfUnused(): void {
  if (currentTelegramEnv() === null) removeTelegramEnvFile(telegramEnvFilePath(resolve(getDataPath())));
}

function assertEnvName(name: string): void {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`Refusing to write an invalid environment variable name: ${name}`);
}

function getAutostartFilePath(): string {
  if (process.platform === 'darwin') return join(homedir(), 'Library', 'LaunchAgents', `${MACOS_LABEL}.plist`);
  if (process.platform === 'linux')
    return join(process.env.XDG_CONFIG_HOME ?? join(homedir(), '.config'), 'systemd', 'user', LINUX_UNIT_NAME);
  if (process.platform === 'win32') return getWindowsLauncherPath();
  throw new Error(`OpenButler automatic startup is not supported on ${process.platform}.`);
}

function getWindowsLauncherPath(): string {
  return resolve(getDataPath(join('autostart', 'openbutler-logon.vbs')));
}

function getCliCommand(): { executable: string; entry: string } {
  const entry = process.argv[1];
  if (!entry) throw new Error('Could not locate the OpenButler CLI entry point.');
  if (/\.tsx?$/i.test(entry)) throw new Error('Build OpenButler and run its compiled CLI before installing automatic startup.');
  return { executable: resolve(process.execPath), entry: resolve(entry) };
}

function assertManagedFileCanBeReplaced(path: string): void {
  if (!existsSync(path)) return;
  if (!readFileSync(path, 'utf8').includes(MANAGED_MARKER)) {
    throw new Error(`Refusing to overwrite an existing user service file: ${path}`);
  }
}

function writeAtomically(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const temporaryPath = `${path}.${process.pid}.tmp`;
  writeFileSync(temporaryPath, content, { encoding: 'utf8', mode: 0o600 });
  try {
    unlinkSync(path);
  } catch {
    /* first install */
  }
  renameSync(temporaryPath, path);
}

function unlinkIfExists(path: string): void {
  try {
    unlinkSync(path);
  } catch (error) {
    if (isRecord(error) && error.code !== 'ENOENT') throw error;
  }
}

function readWindowsRunValue(): string | null {
  const result = spawnSync('reg.exe', ['query', WINDOWS_RUN_KEY, '/v', WINDOWS_RUN_VALUE], { encoding: 'utf8', windowsHide: true });
  if (result.status !== 0) return null;
  return `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
}

function runCommand(command: string, args: string[]): void {
  const result = spawnSync(command, args, { encoding: 'utf8', windowsHide: true, timeout: 30_000 });
  if (result.error) throw new Error(`${command} failed: ${result.error.message}`);
  if (result.status !== 0) {
    const output = `${result.stderr ?? ''}${result.stdout ?? ''}`.trim();
    throw new Error(`${command} exited with code ${String(result.status)}.${output ? ` ${output}` : ''}`);
  }
}

function systemdQuote(value: string, escapeDollar = true): string {
  if (/[\r\n\0]/.test(value)) throw new Error('Service command contains a line break.');
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%');
  return `"${escapeDollar ? escaped.replace(/\$/g, () => '$$') : escaped}"`;
}

function quoteWindowsArgument(value: string): string {
  if (!/[\s"]/.test(value)) return value;
  let result = '"';
  let slashes = 0;
  for (const character of value) {
    if (character === '\\') {
      slashes += 1;
      continue;
    }
    if (character === '"') result += '\\'.repeat(slashes * 2 + 1) + '"';
    else result += '\\'.repeat(slashes) + character;
    slashes = 0;
  }
  return result + '\\'.repeat(slashes * 2) + '"';
}

function xmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function requireUid(): number {
  const uid = process.getuid?.();
  if (!Number.isSafeInteger(uid) || uid === undefined) throw new Error('Could not determine the current macOS user id.');
  return uid;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}
